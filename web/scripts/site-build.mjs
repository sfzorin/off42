// Records and checks the provenance of the web app copy that off42.cc serves from website/public/app.
// Cloudflare's build runs Node only and cannot compile Rust, so the built app is committed; BUILD.txt next to it
// records a hash of the sources it was built from and the SHA-256 of every published file.
//
//   node scripts/site-build.mjs record <dir>   write <dir>/BUILD.txt (publish-to-site.sh does this)
//   node scripts/site-build.mjs check <dir>    fail if the sources changed since <dir> was built, or if the
//                                              published files differ from the ones BUILD.txt lists
//
// Include the reachable Rust workspace crates and their embedded resources, plus the app and its tool schemas.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MAX_FILE = 25 * 1024 * 1024; // Cloudflare Workers static asset limit per file

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

const posix = (path) => relative(repo, path).split(sep).join('/');
const sha256 = (data) => createHash('sha256').update(data).digest('hex');

export function sourceFiles() {
  const web = join(repo, 'web');
  const paths = new Set();
  const seen = new Set();
  const rust = join(repo,'rust');
  function crate(dir) {
    dir = resolve(dir);
    if (seen.has(dir)) return;
    seen.add(dir);
    const manifest = join(dir,'Cargo.toml');
    paths.add(manifest);
    const contents = readFileSync(manifest,'utf8');
    for (const match of contents.matchAll(/\bpath\s*=\s*"([^"]+)"/g)) {
      const target = resolve(dir,match[1]);
      if (existsSync(join(target,'Cargo.toml'))) crate(target);
    }
    for (const file of walk(join(dir,'src'))) {
      paths.add(file);
      if (!file.endsWith('.rs')) continue;
      for (const match of readFileSync(file,'utf8').matchAll(/include_(?:bytes|str)!\(\s*"([^"]+)"/g)) {
        paths.add(resolve(dirname(file),match[1]));
      }
    }
    if(existsSync(join(dir,'build.rs'))) paths.add(join(dir,'build.rs'));
  }
  crate(join(rust,'crates/off42-wasm'));
  for (const path of [join(rust,'Cargo.toml'),join(rust,'Cargo.lock'),
    ...['index.html','package.json','package-lock.json','tsconfig.json','vite.config.ts','scripts/build-wasm.sh','scripts/tool-pages.mjs','scripts/site-build.mjs'].map(f=>join(web,f)),
    ...walk(join(web,'src')).filter(f=>!posix(f).startsWith('web/src/wasm/')), ...walk(join(web,'public')),
    ...walk(join(repo,'assistant/tools')),join(repo,'assistant/eval/lib/schema.mjs')]) paths.add(path);
  return [...paths].map(posix).filter(f=>!f.endsWith('.DS_Store')).sort();
}

export function sourceHash() {
  const lines = sourceFiles().map((f) => `${f} ${sha256(readFileSync(join(repo, f)))}\n`);
  return sha256(lines.join(''));
}

function publishedFiles(dir) {
  return walk(dir).map((f) => relative(dir, f).split(sep).join('/')).filter((f) => f !== 'BUILD.txt' && !f.endsWith('.DS_Store')).sort();
}

function record(dir) {
  const files = publishedFiles(dir).map((f) => {
    const data = readFileSync(join(dir, f));
    if (data.length > MAX_FILE) throw new Error(`${f} is ${data.length} bytes, over the 25 MiB static asset limit`);
    return `${sha256(data)}  ${data.length}  ${f}`;
  });
  const text = [
    '# The OFF42 web app as published on off42.cc/app/. Generated by web/scripts/publish-to-site.sh; do not edit.',
    '# Checked in CI by `node web/scripts/site-build.mjs check website/public/app`.',
    `source-sha256: ${sourceHash()}`,
    `source-files: ${sourceFiles().length} (web app, tool schemas, Rust dependencies and embedded resources)`,
    '# sha256  bytes  file',
    ...files,
    '',
  ].join('\n');
  writeFileSync(join(dir, 'BUILD.txt'), text);
  console.log(text);
}

function check(dir) {
  const problems = [];
  const buildFile = join(dir, 'BUILD.txt');
  if (!existsSync(buildFile)) throw new Error(`${buildFile} is missing: run web/scripts/publish-to-site.sh`);
  const text = readFileSync(buildFile, 'utf8');
  const recorded = text.match(/^source-sha256: ([0-9a-f]{64})$/m)?.[1];
  const current = sourceHash();
  if (recorded !== current) {
    problems.push(`website/public/app was built from other sources (recorded ${recorded}, current ${current}).\n` +
      '  Rebuild and commit it: sh web/scripts/publish-to-site.sh');
  }
  const listed = new Map(text.split('\n').filter((l) => /^[0-9a-f]{64}  /.test(l)).map((l) => {
    const [hash, size, file] = l.split('  ');
    return [file, { hash, size: Number(size) }];
  }));
  const present = publishedFiles(dir);
  for (const file of present) {
    const entry = listed.get(file);
    const data = readFileSync(join(dir, file));
    if (!entry) problems.push(`${file} is not listed in BUILD.txt`);
    else if (entry.hash !== sha256(data)) problems.push(`${file} differs from the file recorded in BUILD.txt`);
    if (statSync(join(dir, file)).size > MAX_FILE) problems.push(`${file} exceeds the 25 MiB static asset limit`);
  }
  for (const file of listed.keys()) if (!present.includes(file)) problems.push(`${file} is listed in BUILD.txt but missing`);
  if (problems.length) {
    console.error(problems.map((p) => `FAIL ${p}`).join('\n'));
    process.exit(1);
  }
  console.log(`ok   website/public/app matches the current sources (${current.slice(0, 12)}…, ${present.length} files)`);
}

const [command, dir] = process.argv.slice(2);
if (command === 'record' && dir) record(resolve(dir));
else if (command === 'check' && dir) check(resolve(dir));
else if (command === 'hash') console.log(sourceHash());
else {
  console.error('usage: node scripts/site-build.mjs record|check <dir> | hash');
  process.exit(2);
}
