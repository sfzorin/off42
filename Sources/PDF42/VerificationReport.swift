import AppKit
import CryptoKit
import Kit42
import PDFKit
import Security

/// Signature verification report as a PDF (signers, certificates and chains, timestamps, PAdES level,
/// long-term validation, integrity), comparable to Acrobat's signature properties printout. Built locally.
enum VerificationReport {
    struct CertificateEntry {
        var certificate: X509
        var isTrustAnchor: Bool
    }

    struct Entry {
        var info: SignatureInfo
        var embedded: PAdES.EmbeddedSignature?
        var revision: Int
        var chain: [CertificateEntry]
        var chainTrusted: Bool
        var chainMessage: String?
        var timestampAuthority: String?
    }

    struct Model {
        var fileName: String
        var fileSize: Int
        var sha256: String
        var pages: Int
        var entries: [Entry]
        var dss: PAdES.DSSContents?
        var completion: CompletionCertificate.Check?
        var created = Date()

        var signatures: [Entry] { entries.filter { !$0.info.isDocumentTimestamp } }
        var timestamps: [Entry] { entries.filter(\.info.isDocumentTimestamp) }
    }

    static func model(_ data: Data, fileName: String) -> Model {
        let bytes = [UInt8](data)
        let infos = PDFSignatureVerifier.verify(data)
        let embedded = PAdES.signatures(in: bytes)
        let aligned = embedded.count == infos.count
        let file = try? PDFFileStructure(data)
        let dss = file.flatMap(PAdES.readDSS)
        let dssCerts = (dss?.certs ?? []).compactMap { X509(der: $0) }
        // Revision number = order of the covered end offsets.
        let ends = Set(embedded.map(\.coveredEnd)).sorted()
        var entries: [Entry] = []
        for (i, info) in infos.enumerated() {
            let sig = aligned ? embedded[i] : nil
            let leaf = info.isDocumentTimestamp ? sig?.cms?.signerCertificate : sig?.cms?.signerCertificate
            let pool = (sig?.certificates ?? []) + dssCerts
            let (chain, trusted, message) = buildChain(leaf: leaf, pool: pool, at: info.timestamp ?? info.date)
            let tsa = info.isDocumentTimestamp ? nil : sig?.cms?.timestampTokens.first?.signerCertificate?.name
            entries.append(Entry(info: info, embedded: sig, revision: sig.flatMap { ends.firstIndex(of: $0.coveredEnd) }.map { $0 + 1 } ?? 0,
                                 chain: chain, chainTrusted: trusted, chainMessage: message, timestampAuthority: tsa))
        }
        return Model(fileName: fileName, fileSize: data.count, sha256: DER.hex([UInt8](SHA256.hash(data: data))),
                     pages: PDFDocument(data: data)?.pageCount ?? 0, entries: entries, dss: dss,
                     completion: CompletionCertificate.check(data))
    }

    /// Path from the signer to a root, built by Security.framework from the embedded and DSS certificates
    /// plus the user's keychains; evaluated at the (trusted) signing time.
    static func buildChain(leaf: X509?, pool: [X509], at date: Date?) -> ([CertificateEntry], Bool, String?) {
        guard let leaf, let leafRef = SecCertificateCreateWithData(nil, Data(leaf.der) as CFData) else { return ([], false, nil) }
        let others = pool.filter { $0 != leaf }.compactMap { SecCertificateCreateWithData(nil, Data($0.der) as CFData) }
        var trust: SecTrust?
        guard SecTrustCreateWithCertificates(([leafRef] + others) as CFArray, SecPolicyCreateBasicX509(), &trust) == errSecSuccess,
              let trust else { return ([CertificateEntry(certificate: leaf, isTrustAnchor: false)], false, nil) }
        SecTrustSetNetworkFetchAllowed(trust, false)
        if let date { SecTrustSetVerifyDate(trust, date as CFDate) }
        var error: CFError?
        let trusted = SecTrustEvaluateWithError(trust, &error)
        let refs = (SecTrustCopyCertificateChain(trust) as? [SecCertificate]) ?? [leafRef]
        var chain = refs.compactMap(X509.init)
        // Complete the path from the pool when Security stops early (e.g. an untrusted root it did not pick up).
        while let last = chain.last, !last.isSelfIssued, let parent = pool.first(where: { $0.subject == last.issuer && !chain.contains($0) }) {
            chain.append(parent)
        }
        let entries = chain.map { CertificateEntry(certificate: $0, isTrustAnchor: trusted && $0 == chain.last) }
        return (entries, trusted, trusted ? nil : (error as Error?)?.localizedDescription)
    }

    // MARK: Rendering

    static func render(_ m: Model) -> Data {
        let r = ReportWriter(title: L("Signature Verification Report"))
        r.footer = L("Signature verification report · %@ · generated by PDF42 on this computer", m.fileName)
        r.newPage()
        r.text(L("Signature Verification Report"), size: 20, weight: .bold, color: ReportWriter.accent, after: 2)
        r.text(L("Generated %@ by PDF42. Verification ran locally; no document data left this computer.", stamp(m.created)),
               size: 9, color: ReportWriter.muted, after: 12)

        r.text(L("Document"), size: 13, weight: .semibold, after: 6)
        r.field(L("File"), m.fileName)
        r.field(L("Size"), L("%@ bytes", m.fileSize.formatted()) + " · " + L("%d pages", m.pages))
        r.field("SHA-256", grouped(m.sha256), mono: true)
        r.space(6)

        // Overall verdict.
        let sigs = m.signatures
        let invalid = m.entries.contains { $0.info.status == .invalid }
        let untrusted = m.entries.contains { $0.info.status == .untrusted || $0.info.status == .notChecked }
        let extended = m.entries.last.map { !$0.info.coversWholeFile } ?? false
        if m.entries.isEmpty {
            r.badge(L("NONE"), color: ReportWriter.muted, text: L("This document has no digital signatures"))
        } else if invalid {
            r.badge(L("INVALID"), color: ReportWriter.bad, text: L("At least one signature is invalid"))
        } else if untrusted {
            r.badge(L("CHECK"), color: ReportWriter.warn, text: L("Signatures are intact, but not every certificate is trusted on this computer"))
        } else {
            r.badge(L("VALID"), color: ReportWriter.good, text: L("All signatures are valid"))
        }
        r.field(L("Signatures"), "\(sigs.count)")
        r.field(L("Document timestamps"), "\(m.timestamps.count)")
        if !m.entries.isEmpty {
            r.field(L("Changes after signing"), extended ? L("Yes: content was added after the last signature or timestamp")
                                                         : L("None: the last signature covers the whole file"),
                    color: extended ? ReportWriter.warn : ReportWriter.ink)
        }
        if let dss = m.dss {
            r.field(L("Validation data (DSS)"), L("%d certificates, %d OCSP responses, %d CRLs", dss.certs.count, dss.ocsps.count, dss.crls.count))
        } else if !m.entries.isEmpty {
            r.field(L("Validation data (DSS)"), L("None in the document"))
        }
        r.space(8)

        for (i, e) in m.entries.enumerated() {
            r.ensureSpace(140)
            r.rule()
            let title = e.info.isDocumentTimestamp ? L("Document timestamp %d", i + 1) : L("Signature %d: %@", i + 1, e.info.signer)
            r.text(title, size: 13, weight: .semibold, after: 6)
            let (label, color) = statusBadge(e.info)
            r.badge(label, color: color, text: e.info.summary)
            r.field(e.info.isDocumentTimestamp ? L("Time-stamping authority") : L("Signer"), e.info.signer)
            if let email = e.info.email { r.field(L("Email"), email) }
            if let d = e.info.date, !e.info.isDocumentTimestamp { r.field(L("Signing time (claimed)"), stamp(d)) }
            if let t = e.info.timestamp {
                r.field(L("Trusted timestamp"), stamp(t) + (e.timestampAuthority.map { " · " + $0 } ?? ""))
            } else if !e.info.isDocumentTimestamp {
                r.field(L("Trusted timestamp"), L("None: the time is the signer's computer clock"), color: ReportWriter.muted)
            }
            if let level = e.info.level { r.field(L("Format"), level + (e.embedded?.subFilter.map { " (\($0))" } ?? "")) }
            if let ltv = e.info.ltvEnabled {
                r.field(L("Long-term validation"), ltv ? L("Enabled") : L("Not enabled: %@", e.info.ltvProblem ?? ""),
                        color: ltv ? ReportWriter.good : ReportWriter.warn)
            }
            if let reason = e.info.reason { r.field(L("Reason"), reason) }
            if let location = e.info.location { r.field(L("Location"), location) }
            if let s = e.embedded {
                r.field(L("Signed revision"), L("Revision %d: bytes 0–%@ of %@", e.revision, s.coveredEnd.formatted(), m.fileSize.formatted()))
            }
            r.field(L("Integrity"), integrity(e.info), color: e.info.status == .invalid ? ReportWriter.bad : ReportWriter.ink)
            r.field(L("Certificate trust"), e.chainTrusted ? L("Trusted on this computer") : (e.info.trustMessage ?? e.chainMessage ?? L("Not trusted on this computer")),
                    color: e.chainTrusted ? ReportWriter.good : ReportWriter.warn)
            if !e.chain.isEmpty {
                r.space(4)
                r.text(L("Certificate chain"), size: 10.5, weight: .semibold, after: 4)
                for (k, c) in e.chain.enumerated() { certificate(c, index: k, writer: r) }
            }
            r.space(6)
        }

        if let c = m.completion {
            r.ensureSpace(120)
            r.rule()
            r.text(L("Certificate of completion"), size: 13, weight: .semibold, after: 6)
            r.badge(c.matches ? L("MATCH") : L("MISMATCH"), color: c.matches ? ReportWriter.good : ReportWriter.bad,
                    text: c.matches ? L("The document hash on the certificate page matches the signed document")
                                    : L("The document hash on the certificate page does not match"))
            r.field(L("Recorded SHA-256"), grouped(c.payload.sha256), mono: true)
            r.field(L("Covered bytes"), c.payload.length.formatted())
            r.field(L("Read from"), c.source == .qr ? L("QR code") : L("page text"))
        }
        r.space(10)
        r.text(L("How to read this report: “valid” means the signed bytes are unchanged and the certificate chain is trusted by this computer at the signing time. Trust depends on the certificates installed in this Mac's keychains; a self-signed certificate is reported as intact but not trusted."),
               size: 8, color: ReportWriter.muted)
        return r.finish()
    }

    private static func certificate(_ c: CertificateEntry, index: Int, writer r: ReportWriter) {
        let x = c.certificate
        r.ensureSpace(80)
        let role = index == 0 ? L("Signer certificate") : c.isTrustAnchor || x.isSelfIssued ? L("Root certificate") : L("Intermediate certificate")
        r.text("\(index + 1). \(role)", size: 9.5, weight: .semibold, color: ReportWriter.accent, indent: 12, after: 2)
        r.field(L("Subject"), x.subjectName, indent: 12)
        r.field(L("Issuer"), x.issuerName, indent: 12)
        r.field(L("Serial number"), x.serialHex, mono: true, indent: 12)
        r.field(L("Valid"), "\(x.notBefore.map(stamp) ?? "?") — \(x.notAfter.map(stamp) ?? "?")", indent: 12)
        r.field(L("Public key"), x.keyDescription, indent: 12)
        r.field(L("SHA-256 fingerprint"), x.fingerprint, mono: true, indent: 12)
        r.space(3)
    }

    static func statusBadge(_ info: SignatureInfo) -> (String, NSColor) {
        switch info.status {
        case .valid: return (L("VALID"), ReportWriter.good)
        case .untrusted: return (L("CHECK"), ReportWriter.warn)
        case .invalid: return (L("INVALID"), ReportWriter.bad)
        case .notChecked: return (L("NOT CHECKED"), ReportWriter.warn)
        }
    }

    static func integrity(_ info: SignatureInfo) -> String {
        if info.status == .invalid { return info.problem ?? L("Signature is invalid") }
        return info.coversWholeFile ? L("Intact: the signed bytes are unchanged and cover the whole file")
                                    : L("Intact for its revision; later revisions were appended")
    }

    static func stamp(_ d: Date) -> String { SignatureAppearance.dateFormatter.string(from: d) }

    static func grouped(_ hex: String) -> String {
        stride(from: 0, to: hex.count, by: 8).map { i -> String in
            let s = hex.index(hex.startIndex, offsetBy: i)
            return String(hex[s..<hex.index(s, offsetBy: min(8, hex.count - i))])
        }.joined(separator: " ")
    }
}

extension EditorWindowController {
    /// Signature ▸ Export Verification Report…
    @objc func exportVerificationReportAction(_ sender: Any?) {
        guard let doc = pdfDoc, let window else { return }
        guard let data = doc.originalData ?? doc.fileURL.flatMap({ try? Data(contentsOf: $0) }) else { return }
        let name = doc.fileURL?.lastPathComponent ?? doc.displayName ?? L("Document")
        let report = VerificationReport.render(VerificationReport.model(data, fileName: name))
        let panel = NSSavePanel()
        panel.allowedContentTypes = [.pdf]
        panel.nameFieldStringValue = L("%@ (verification report).pdf", doc.fileURL?.deletingPathExtension().lastPathComponent ?? name)
        panel.directoryURL = doc.fileURL?.deletingLastPathComponent()
        panel.beginSheetModal(for: window) { response in
            guard response == .OK, let url = panel.url else { return }
            do {
                try report.write(to: url)
                NSDocumentController.shared.openDocument(withContentsOf: url, display: true) { _, _, _ in }
            } catch { self.presentError(error) }
        }
    }
}
